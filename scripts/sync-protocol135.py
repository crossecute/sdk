"""Refresh the unreleased protocol compatibility snapshot from an exact checkout + Forge artifacts."""
import json, pathlib, subprocess, sys
root = pathlib.Path(__file__).resolve().parents[1]
protocol = pathlib.Path(sys.argv[1]).resolve()
revision = '5d7be13e3afccb88c8a1b8a298bc56709706f76c'
if subprocess.check_output(['git', '-C', str(protocol), 'rev-parse', 'HEAD'], text=True).strip() != revision:
    raise SystemExit('Expected protocol revision ' + revision)
files = {
    'contracts/safe-guard/src/ICrossecuteGuard.sol': 'ICrossecuteGuard.sol',
    'contracts/safe-guard/src/SafeHashes.sol': 'SafeHashes.sol',
    'contracts/safe-guard/src/SafeBatchExecutor.sol': 'SafeBatchExecutor.sol',
    'contracts/evm/src/messaging/signed/types/SafeAuthorityTypes.sol': 'SafeAuthorityTypes.sol',
    'contracts/evm/src/messaging/signed/types/SignedDispatchTypes.sol': 'SignedDispatchTypes.sol',
    'contracts/evm/src/messaging/signed/DispatchLeaves.sol': 'DispatchLeaves.sol',
    'contracts/evm/src/messaging/outbound/ISignedTransmitter.sol': 'ISignedTransmitter.sol',
    'contracts/evm/src/messaging/inbound/ISignedReceiver.sol': 'ISignedReceiver.sol',
}
import re, hashlib
manifest = {'repository': 'https://github.com/crossecute/protocol', 'revision': revision, 'sources': {}}
for source, name in files.items():
    original = (protocol / source).read_text()
    committed = subprocess.check_output(['git', '-C', str(protocol), 'show', revision + ':' + source], text=True)
    if original != committed:
        raise SystemExit('Refusing modified protocol source: ' + source)
    text = re.sub(r'"(?:@crossecute/safe-guard/|src/messaging/signed/types/|\.\./signed/types/)([^"/]+)"', r'"./\1"', original)
    (root / 'contracts/vendor/protocol135' / name).write_text(text)
    manifest['sources'][source] = hashlib.sha256(original.encode()).hexdigest()
(root / 'contracts/vendor/protocol135/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
exports = '// Generated by scripts/sync-protocol135.py; protocol ' + revision + '.\n'
for name, folder in [('SignedTransmitter', 'evm'), ('ISignedReceiver', 'evm'), ('ICrossecuteGuard', 'safe-guard'), ('SafeBatchExecutor', 'safe-guard')]:
    artifact = json.loads((protocol / f'contracts/{folder}/out/{name}.sol/{name}.json').read_text())
    # Export the complete ABI so events, views, and custom errors are available to viem.
    export_name = {'ISignedReceiver': 'signedReceiver', 'ICrossecuteGuard': 'crossecuteGuard'}.get(name, name[0].lower() + name[1:])
    exports += 'export const ' + export_name + 'Abi = ' + json.dumps(artifact['abi'], separators=(',', ':')) + ' as const;\n'
(root / 'ts/src/signedAbi.ts').write_text(exports)
