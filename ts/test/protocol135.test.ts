import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { basename } from "node:path";
import { describe, expect, it } from "vitest";
import * as sdk from "../src/index.js";
import { PROTOCOL_135_REVISION } from "../src/signedAbi.js";

const root = new URL("../../", import.meta.url);
const read = (path: string) => readFileSync(new URL(path, root), "utf8");
const vendorDir = "contracts/vendor/protocol135/";
const manifest = JSON.parse(read(vendorDir + "manifest.json")) as {
  repository: string; revision: string; sources: Record<string, string>; vendored: Record<string, string>;
};
const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");
const vendoredFiles = readdirSync(new URL(vendorDir, root)).filter((f) => f.endsWith(".sol")).sort();

// Refresh with scripts/sync-protocol135.py; `--check <protocol checkout>` compares against the pinned revision itself.
describe("protocol #135 snapshot", () => {
  it("pins one full revision that every record of it repeats", () => {
    expect(manifest.revision).toMatch(/^[0-9a-f]{40}$/);
    expect(PROTOCOL_135_REVISION).toBe(manifest.revision);
    expect(sdk.PROTOCOL_135_REVISION).toBe(manifest.revision);
    expect(read("ts/src/signedAbi.ts").split("\n")[0]).toBe(`// Generated by scripts/sync-protocol135.py; protocol ${manifest.revision}.`);
    expect(read("scripts/sync-protocol135.py")).toContain(`REVISION = '${manifest.revision}'`);
    expect(JSON.parse(read("vectors/authority.json")).revision).toBe(manifest.revision);
    expect(read("README.md")).toContain(`${manifest.repository}/commit/${manifest.revision}`);
    expect(read(vendorDir + "README.md")).toContain(`\`${manifest.revision}\``);
  });

  it("vendors exactly the sources it lists, unmodified apart from import specifiers", () => {
    const names = Object.keys(manifest.sources).map((source) => basename(source)).sort();
    expect(new Set(names).size).toBe(names.length);
    expect(vendoredFiles).toEqual(names);
    expect(Object.keys(manifest.vendored).sort()).toEqual(names);
    for (const name of vendoredFiles) {
      const text = read(vendorDir + name);
      expect(sha256(text), name).toBe(manifest.vendored[name]);
      expect(text, name).not.toMatch(/from "(?:@crossecute|src)\//);
    }
    for (const source of Object.keys(manifest.sources)) expect(read("scripts/sync-protocol135.py")).toContain(`'${source}'`);
  });

  it("records source hashes for unmodified protocol files", () => {
    for (const hash of Object.values(manifest.sources)) expect(hash).toMatch(/^[0-9a-f]{64}$/);
    // A file whose imports needed no rewrite is byte for byte the protocol source.
    for (const [source, hash] of Object.entries(manifest.sources)) {
      const text = read(vendorDir + basename(source));
      if (!/from "\./.test(text)) expect(sha256(text), source).toBe(hash);
    }
  });

  it("exports the generated ABIs the builders read", () => {
    for (const name of ["signedTransmitterAbi", "signedReceiverAbi", "transceiverExtensionAbi", "transceiverBaseAbi", "conduitTransceiverAbi", "crossecuteGuardAbi", "safeBatchExecutorAbi"]) {
      expect(sdk).toHaveProperty(name);
    }
    const names = (abi: readonly { type: string; name?: string }[]) => abi.filter((f) => f.type === "function").map((f) => f.name);
    expect(names(sdk.signedTransmitterAbi)).toEqual(expect.arrayContaining(["bootstrap", "registerRoot", "relayLeaf", "relayAuthority", "quoteAuthority", "isSigned", "sendMessage"]));
    expect(names(sdk.signedReceiverAbi)).toEqual(expect.arrayContaining(["graph", "selection", "submitMessage", "submitLeaf", "initializeSigned"]));
    expect(names(sdk.crossecuteGuardAbi)).toContain("publishLeaves");
    const inputs = (abi: readonly any[], name: string) => abi.find((f) => f.type === "function" && f.name === name)?.inputs.length;
    expect(inputs(sdk.signedTransmitterAbi, "initializeSigned")).toBe(0);
    expect(inputs(sdk.signedReceiverAbi, "initializeSigned")).toBe(3);
    expect(names(sdk.signedReceiverAbi)).not.toContain("bootstrapGraph");
  });
});
