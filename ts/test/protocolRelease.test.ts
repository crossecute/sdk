import { readFileSync } from "node:fs";
import { IConduitTransceiverAbi, ICrossecuteGuardAbi } from "@crossecute/protocol/abi";
import { describe, expect, it } from "vitest";
import * as sdk from "../src/index.js";
import { PROTOCOL_VERSION } from "../src/signedAbi.js";

const root = new URL("../../", import.meta.url);
const read = (path: string) => readFileSync(new URL(path, root), "utf8");
const script = read("scripts/sync-protocol.py");
const scriptPin = (name: string) => new RegExp(`^${name} = '([^']+)'`, "m").exec(script)?.[1];

// Refresh with scripts/sync-protocol.py; `--check <protocol checkout>` compares against the pinned release itself.
describe("protocol release pin", () => {
  it("names one release that every record of it repeats", () => {
    const version = scriptPin("VERSION");
    const revision = scriptPin("REVISION");
    expect(version).toMatch(/^\d+\.\d+\.\d+$/);
    expect(revision).toMatch(/^[0-9a-f]{40}$/);
    expect(PROTOCOL_VERSION).toBe(version);
    expect(sdk.PROTOCOL_VERSION).toBe(version);
    expect(JSON.parse(read("package.json")).dependencies["@crossecute/protocol"]).toBe(version);
    expect(read("ts/src/signedAbi.ts").split("\n")[0]).toBe(
      `// Generated by scripts/sync-protocol.py; @crossecute/protocol ${version}, protocol ${revision}.`,
    );
    expect(JSON.parse(read("vectors/authority.json")).revision).toBe(revision);
    expect(JSON.parse(read("vectors/lzoft-protocol.json")).revision).toBe(revision);
  });

  it("compiles against the installed release it pins", () => {
    const installed = JSON.parse(read("node_modules/@crossecute/protocol/package.json"));
    expect(installed.version).toBe(PROTOCOL_VERSION);
  });

  it("derives tuple layouts with the member names and order the encoders assume", () => {
    type Node = { name?: string; type: string; components?: readonly Node[] };
    const fn = (abi: readonly any[], name: string) => abi.find((f) => f.type === "function" && f.name === name);
    const names = (n: Node | undefined) => n?.components?.map((c) => c.name);
    const [evidence, leaf] = fn(sdk.signedTransmitterAbi, "relayLeaf").inputs as Node[];
    expect(names(leaf)).toEqual(["destination", "nonce", "validAfter", "deadline", "calls", "attributes"]);
    expect(names(evidence)).toEqual(["signedSafeTx", "nestedApprovals"]);
    const graph = fn(sdk.signedReceiverAbi, "graph").outputs[0] as Node;
    expect(graph.type).toBe("tuple");
    expect(names(graph)).toEqual(["nodes"]);
    expect(names(graph.components![0])).toEqual(["record", "position"]);
    const record = graph.components![0].components![0];
    expect(names(record)).toEqual(["safe", "threshold", "owners"]);
    expect(names(record.components![2])).toEqual(["owner", "kind"]);
  });

  it("keeps every function the README and the builders use in the trimmed ABIs", () => {
    const has = (abi: readonly { type: string; name?: string }[], ...fns: string[]) => {
      const present = abi.filter((f) => f.type === "function").map((f) => f.name);
      for (const fn of fns) expect(present, fn).toContain(fn);
    };
    has(sdk.signedTransmitterAbi, "quoteBootstrap", "quoteRelay", "relayAuthority", "quoteAuthority", "isSigned", "relayLeaf", "registerRoot", "quoteMessageSigned", "sendMessage", "bootstrap");
    has(sdk.signedReceiverAbi, "selection", "graph", "submitLeaf", "submitMessage", "submitAuthority");
    has(sdk.transceiverBaseAbi, "predictReceiver", "bootstrapSigned", "quoteBootstrapSigned");
    has(sdk.conduitTransceiverAbi, "predictReceiver", "signedAuthority");
    has(sdk.transceiverExtensionAbi, "predictConduit", "signedAuthority");
    has(sdk.crossecuteGuardAbi, "publishLeaves");
    has(sdk.safeBatchExecutorAbi, "execute");
    has(sdk.lzOftConduitFactoryAbi, "createTransmitter", "predictConduit", "conduitSalt", "PROXY_INIT_CODE_HASH", "isSigned", "predictReceiver", "signedConduitBootstrap");
    has(sdk.lzOftTransmitterAbi, "homeOft", "destinationOf", "supportsAttribute", "LZ_OPTIONS_ATTRIBUTE");
    has(sdk.lzOftReceiverAbi, "homeOft", "localOft");
    for (const abi of [sdk.signedTransmitterAbi, sdk.signedReceiverAbi, sdk.transceiverBaseAbi, sdk.transceiverExtensionAbi, sdk.lzOftConduitFactoryAbi, sdk.lzOftTransmitterAbi, sdk.lzOftReceiverAbi]) {
      expect(abi.some((f) => f.type === "error")).toBe(true);
      expect(abi.filter((f) => f.type === "function").map((f) => f.name)).not.toContain("grantRole");
    }
  });

  it("keeps the OFT factory's creation errors, with the leaf ordering rule, in the ABI", () => {
    const errors = sdk.lzOftConduitFactoryAbi.filter((f) => f.type === "error").map((f) => f.name);
    expect(errors).toEqual(expect.arrayContaining(["NoDestinations", "LeavesNotSorted", "BadLeaf", "NotAnOft"]));
    const create = sdk.lzOftConduitFactoryAbi.find((f) => f.type === "function" && f.name === "createTransmitter")!;
    expect(create.inputs.map((i) => i.name)).toEqual(["salt", "homeOft", "leaves"]);
    expect((create.inputs[2] as any).components.map((c: any) => `${c.name}:${c.type}`)).toEqual(["chainKey:bytes32", "eid:uint32", "oft:address"]);
  });

  it("exports the protocol ABIs the builders read", () => {
    for (const name of ["signedTransmitterAbi", "signedReceiverAbi", "transceiverExtensionAbi", "transceiverBaseAbi", "conduitTransceiverAbi", "crossecuteGuardAbi", "safeBatchExecutorAbi", "lzOftConduitFactoryAbi", "lzOftTransmitterAbi", "lzOftReceiverAbi"]) {
      expect(sdk).toHaveProperty(name);
    }
    expect(sdk.conduitTransceiverAbi).toBe(IConduitTransceiverAbi);
    expect(sdk.crossecuteGuardAbi).toBe(ICrossecuteGuardAbi);
    const names = (abi: readonly { type: string; name?: string }[]) => abi.filter((f) => f.type === "function").map((f) => f.name);
    expect(names(sdk.signedTransmitterAbi)).toEqual(expect.arrayContaining(["bootstrap", "registerRoot", "relayLeaf", "relayAuthority", "quoteAuthority", "isSigned", "sendMessage"]));
    expect(names(sdk.signedReceiverAbi)).toEqual(expect.arrayContaining(["graph", "selection", "submitMessage", "submitLeaf", "initializeSigned"]));
    expect(names(sdk.crossecuteGuardAbi)).toContain("publishLeaves");
    const inputs = (abi: readonly any[], name: string) => abi.find((f) => f.type === "function" && f.name === name)?.inputs.length;
    expect(inputs(sdk.signedTransmitterAbi, "initializeSigned")).toBe(0);
    expect(inputs(sdk.signedReceiverAbi, "initializeSigned")).toBe(3);
    expect(names(sdk.signedReceiverAbi)).not.toContain("bootstrapGraph");
  });
});
